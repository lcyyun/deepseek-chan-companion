'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const net = require('node:net');
const { spawn, execFileSync } = require('node:child_process');

const DEFAULT_PORT = 63616;

function expandHome(value) {
  if (typeof value !== 'string' || !value.trim()) return '';
  return value.trim().replace(/^~(?=$|[\\/])/, os.homedir());
}

function resolveHome(config = {}) {
  return path.resolve(expandHome(config.dshHome || process.env.DSH_HOME || path.join(os.homedir(), '.dsh')));
}

function resolveCli(config = {}) {
  const candidates = [];
  if (config.dshCli) candidates.push(expandHome(config.dshCli));
  if (process.env.DSH_CLI) candidates.push(expandHome(process.env.DSH_CLI));
  candidates.push(path.join(process.env.ProgramFiles || 'C:\\Program Files', 'DeepSeek Harness', 'resources', 'runtime', 'cli', 'bin', 'dsh.cmd'));
  candidates.push(path.join('D:\\Programs', 'DeepSeek Harness', 'resources', 'runtime', 'cli', 'bin', 'dsh.cmd'));
  for (const candidate of candidates) {
    try { if (candidate && fs.statSync(candidate).isFile()) return candidate; } catch {}
  }
  try {
    const found = execFileSync('where.exe', ['dsh'], { encoding: 'utf8', windowsHide: true }).split(/\r?\n/).map(s => s.trim()).find(Boolean);
    if (found) return found;
  } catch {}
  return '';
}

function portOpen(port, timeout = 450) {
  return new Promise(resolve => {
    const socket = net.connect({ host: '127.0.0.1', port });
    const done = value => { socket.destroy(); resolve(value); };
    socket.setTimeout(timeout, () => done(false));
    socket.once('connect', () => done(true));
    socket.once('error', () => done(false));
  });
}

async function detectDsh(config = {}) {
  const cli = resolveCli(config);
  const home = resolveHome(config);
  const configuredPort = Number(config.dshPort) || DEFAULT_PORT;
  // A custom DSH_HOME is an explicit test/advanced instance. Probe its own port
  // first and do not mistake the user's default DSH on 53180 for it.
  const ports = [...new Set(config.dshHome ? [configuredPort] : [53180, configuredPort, 63616])];
  const open = [];
  for (const port of ports) if (await portOpen(port)) open.push(port);
  return { cli, home, port: configuredPort, open, running: open.length > 0, homeExists: fs.existsSync(home) };
}

function quote(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function patchText({ root, dataDir, serviceUrl, token, mode, sessionId, sessionFile, port }) {
  const bridge = path.join(root, 'integrations', 'dsh', 'live2d-bridge.mjs');
  const tokenFile = path.join(dataDir, 'bridge-token');
  const tokenPath = tokenFile.replace(/\\/g, '/');
  const authorization = `!!js '\`Bearer \${process.getBuiltinModule("node:fs").readFileSync(${JSON.stringify(tokenPath)},"utf8").trim()}\`'`;
  const lines = [
    '# Generated by DeepSeek-chan. It reads the local pairing token from tokenFile; keep both files private.',
    '- insert:',
    '    - id: live2d-mcp',
    "      name: '@deepseek-ai/dsh-mcp-client'",
    '      config:',
    '        serverName: live2d',
    '        transport: streamable-http',
    `        url: ${quote(String(serviceUrl).replace(/\/$/, '') + '/mcp')}`,
    '        headers:',
    `          Authorization: ${authorization}`,
    '    - id: live2d-state-bridge',
    `      name: ${quote(bridge)}`,
    '      config:',
    `        baseUrl: ${quote(String(serviceUrl).replace(/\/$/, ''))}`,
    '        chat: true',
    '        native: true',
    `        tokenFile: ${quote(tokenFile)}`,
    '        searchTools: []',
  ];
  if (mode === 'existing') {
    if (!/^session-[A-Za-z0-9-]+$/.test(String(sessionId || ''))) throw new Error('会话 ID 格式不正确。');
    lines.push(`        chatSessionId: ${quote(sessionId)}`);
  } else {
    lines.push(`        sessionFile: ${quote(sessionFile)}`);
  }
  lines.push(`        # DSH web port: ${port}`, '');
  return lines.join('\n');
}

function writePatch(options) {
  const file = path.join(options.dataDir, 'dsh', 'live2d.patch.yml');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, patchText(options), { encoding: 'utf8', mode: 0o600 });
  return file;
}

function sessionFile(dataDir) {
  return path.join(dataDir, 'dsh', 'chat-session.txt');
}

function listSessions(home, limit = 20) {
  const root = path.join(home, 'sessions');
  const found = [];
  const visit = dir => {
    let entries;
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (!entry.isDirectory()) continue;
      if (/^session-[A-Za-z0-9-]+$/.test(entry.name)) {
        let mtime = 0;
        try { mtime = fs.statSync(path.join(full, 'session.v4.jsonl.zstd')).mtimeMs; } catch {}
        found.push({ id: entry.name, updatedAt: mtime, cwd: path.basename(dir) });
      } else visit(full);
    }
  };
  visit(root);
  return found.sort((a, b) => b.updatedAt - a.updatedAt).slice(0, limit);
}

function startDsh({ cli, home, patch, port, logFile }) {
  if (!cli || !fs.existsSync(cli)) throw new Error('没有找到 DSH CLI。');
  if (!fs.existsSync(home)) throw new Error(`DSH_HOME 不存在：${home}`);
  fs.mkdirSync(path.dirname(logFile), { recursive: true });
  const log = fs.openSync(logFile, 'a');
  const args = ['web', '--patch', patch, '--port', String(port), '--no-open'];
  const env = { ...process.env, DSH_HOME: home };
  const command = `"${cli}" web --patch "${patch}" --port ${Number(port)} --no-open`;
  const child = /\.(?:cmd|bat)$/i.test(cli)
    ? spawn(command, {
      cwd: home, env, detached: true, windowsHide: true, stdio: ['ignore', log, log], shell: true,
    })
    : spawn(cli, args, {
      cwd: home, env, detached: true, windowsHide: true, stdio: ['ignore', log, log],
    });
  child.unref();
  fs.closeSync(log);
  return child;
}

function waitForPort(port, timeout = 30000) {
  const started = Date.now();
  return new Promise((resolve, reject) => {
    const tick = async () => {
      if (await portOpen(port)) return resolve(true);
      if (Date.now() - started >= timeout) return reject(new Error('DSH 在限定时间内没有启动。'));
      setTimeout(tick, 300);
    };
    tick();
  });
}

async function waitForBridge(service, timeout = 30000) {
  const started = Date.now();
  while (Date.now() - started < timeout) {
    const state = service.getState();
    if (state.dsh?.connected && state.dsh?.chatAvailable) return state;
    await new Promise(r => setTimeout(r, 300));
  }
  throw new Error('DSH 已启动，但皮套聊天桥没有就绪。请检查 DSH 的模型配置和插件日志。');
}

module.exports = { DEFAULT_PORT, resolveHome, resolveCli, detectDsh, patchText, writePatch, sessionFile, listSessions, startDsh, waitForPort, waitForBridge };
